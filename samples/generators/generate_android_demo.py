#!/usr/bin/env python3
"""Embed the fictional expanded sample as Kotlin strings; no build or app import."""
import csv
import hashlib
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'samples/data/patients.csv'
OUTPUT = ROOT / 'android/app/src/main/java/com/hos/rushdpatients/ui/demo/DemoSamplePatients.kt'


def generate():
    content = SOURCE.read_bytes()
    rows = list(csv.reader(io.StringIO(content.decode('utf-8-sig'))))
    if len(rows) != 52 or len(rows[1]) != 24 or any(len(row) != 24 for row in rows[2:]):
        raise ValueError('Expected the current 50-patient, 24-column sample.')
    literals = []
    for row in rows:
        buffer = io.StringIO(newline='')
        csv.writer(buffer, lineterminator='\n').writerow(row)
        record = buffer.getvalue().removesuffix('\n')
        # Separate record literals avoid the JVM's per-string constant limit.
        if len(record.encode('utf-8')) >= 60_000:
            raise ValueError('Sample row is too large for one Kotlin string literal.')
        literals.append('            ' + json.dumps(record, ensure_ascii=False).replace('$', '\\$'))
    text = '''package com.hos.rushdpatients.ui.demo

import com.hos.rushdpatients.data.model.Patient
import com.hos.rushdpatients.sync.CsvCodec

// Generated by samples/generators/generate_android_demo.py; edit the fictional CSV and regenerate.
// Source: samples/data/patients.csv
// SHA-256: %s
// Embedded data only: no runtime file/database/network access. Decode once per process.
internal object DemoSamplePatients {
    val patients: List<Patient> by lazy {
        CsvCodec.decode(listOf(
%s
        ).joinToString("\\n")).patients
    }
}
''' % (hashlib.sha256(content).hexdigest(), ',\n'.join(literals))
    OUTPUT.write_text(text, encoding='utf-8')
    print('Embedded 50 fictional patients from the expanded sample CSV.')


if __name__ == '__main__':
    generate()
